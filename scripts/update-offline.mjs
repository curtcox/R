import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../',import.meta.url),webr='https://cdn.jsdelivr.net/npm/webr@0.6.0/dist/';
const hash=data=>createHash('sha256').update(data).digest('hex');
let assets=['index.html','gallery.html','icon.svg','manifest.webmanifest','svg-pan-zoom.min.js','service-worker.js','LICENSE-graphvizonline','LICENSE-svg-pan-zoom'];
async function walk(directory){for(const entry of await fs.readdir(new URL(directory+'/',root),{withFileTypes:true})){const name=directory+'/'+entry.name;if(entry.isDirectory())await walk(name);else if(!name.endsWith('r-node.mjs'))assets.push(name);}}
for(const directory of ['src','ace','vendor','examples','gallery/previews','icons','docs'])await walk(directory);
assets.sort();
const hashes={};for(const asset of assets)hashes[asset]=hash(await fs.readFile(new URL(asset,root)));
const runtime=JSON.parse(await fs.readFile(new URL('src/runtime-files.json',root)));
const remote={};
for(const name of [...new Set(['webr-worker.js','R.js','R.wasm',...runtime.startup,...runtime.lazy])].sort())remote[webr+name]=hash(await fs.readFile(new URL('node_modules/webr/dist/'+name,root)));
const packages=JSON.parse(await fs.readFile(new URL('scripts/package-hashes.json',root)));
const manifest={version:'ronline-'+hash(JSON.stringify({hashes,remote,packages:packages.hashes})).slice(0,16),webr,assets:[...assets,...Object.keys(remote)],hashes:{...hashes,...remote},packageHashes:packages.hashes};
const source='/** Generated by npm run offline. */\nconst OfflineAssets='+JSON.stringify(manifest,null,2)+';\nif(typeof module!=="undefined")module.exports=OfflineAssets;else globalThis.OfflineAssets=OfflineAssets;\n';
if(process.argv.includes('--check')){
 if(await fs.readFile(new URL('offline-assets.js',root),'utf8')!==source)throw Error('Offline manifest is stale. Run npm run offline.');
 if(await fs.readFile(new URL('scripts/remote-hashes.json',root),'utf8')!==JSON.stringify(remote,null,2)+'\n')throw Error('Remote hashes are stale. Run npm run offline.');
}else{
 await fs.writeFile(new URL('offline-assets.js',root),source);
 await fs.writeFile(new URL('scripts/remote-hashes.json',root),JSON.stringify(remote,null,2)+'\n');
}
console.log(manifest.version+': '+manifest.assets.length+' verified assets');
